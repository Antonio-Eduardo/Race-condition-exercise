CREATE TABLE usuario(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL,
    cpf VARCHAR(11) UNIQUE NOT NULL
);
CREATE TABLE laboratorio(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_laboratorio VARCHAR(6) UNIQUE NOT NULL,
    computadores INTEGER NOT NULL CHECK ( computadores >= 0 )
);
CREATE TABLE reserva(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL,
    laboratorio_id BIGINT NOT NULL REFERENCES laboratorio(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    status VARCHAR(10) NOT NULL,
    cancelado_por BIGINT REFERENCES usuario(id),
    cancelado_em TIMESTAMPTZ,
    CONSTRAINT reserva_periodo_check CHECK ( fim > inicio ),
    CONSTRAINT reserva_status_check CHECK (status IN ('AGENDADA', 'CANCELADA')),
    CONSTRAINT reserva_cancelamento_check CHECK (
        (status = 'AGENDADA' AND cancelado_em IS NULL AND cancelado_por IS NULL)
        OR
        (status = 'CANCELADA' AND cancelado_em IS NOT NULL AND cancelado_por IS NOT NULL))

);
CREATE INDEX idx_reserva_laboratorio_fim ON reserva(laboratorio_id,fim);